var tableBody = document.getElementById("verbTableBody");
var searchInput = document.getElementById("searchInput");
var noResult = document.getElementById("noResult");


function createNote(verb, tense, conjugation, cell, button) {

    var oldNote = document.querySelector(".note-box");

    if (oldNote) {
        oldNote.parentNode.removeChild(oldNote);
    }

    var activeButtons =
        document.querySelectorAll(".verb-button.active");

    var i;

    for (i = 0; i < activeButtons.length; i++) {

        activeButtons[i].className =
            activeButtons[i].className.replace(" active", "");

    }

    var note = document.createElement("div");
    note.className = "note-box";

    var title = document.createElement("div");
    title.className = "note-title";
    title.innerHTML =
        verb.infinitive + " – " + tense;

    note.appendChild(title);

    var persons = [
        ["ich", conjugation.ich],
        ["du", conjugation.du],
        ["er / sie / es", conjugation.er],
        ["wir", conjugation.wir],
        ["ihr", conjugation.ihr],
        ["sie / Sie", conjugation.sie]
    ];

    var j;

    for (j = 0; j < persons.length; j++) {

        var row = document.createElement("div");
        row.className = "note-row";

        var name = document.createElement("span");
        name.innerHTML = persons[j][0];

        var value = document.createElement("strong");
        value.innerHTML = persons[j][1];

        row.appendChild(name);
        row.appendChild(value);
        note.appendChild(row);
    }

    cell.appendChild(note);

    button.className += " active";

    note.onclick = function(event) {
        event.stopPropagation();
    };
}


function displayVerbs(list) {

    tableBody.innerHTML = "";

    if (list.length === 0) {
        noResult.style.display = "block";
        return;
    }

    noResult.style.display = "none";

    var i;

    for (i = 0; i < list.length; i++) {

        var verb = list[i];

        var row = document.createElement("tr");


        /* PRÄSENS */

        var praesensCell = document.createElement("td");

        var praesensButton = document.createElement("button");

        praesensButton.className = "verb-button";

        praesensButton.innerHTML = verb.praesens;

        praesensButton.onclick =
            function(verbData, cellData, buttonData) {

                return function(event) {

                    event.stopPropagation();

                    createNote(
                        verbData,
                        "Präsens",
                        verbData.praesensConj,
                        cellData,
                        buttonData
                    );
                };

            }(
                verb,
                praesensCell,
                praesensButton
            );

        praesensCell.appendChild(praesensButton);


        /* PERFEKT */

        var perfektCell = document.createElement("td");

        var perfektButton = document.createElement("button");

        perfektButton.className = "verb-button";

        perfektButton.innerHTML = verb.perfekt;

        perfektButton.onclick =
            function(verbData, cellData, buttonData) {

                return function(event) {

                    event.stopPropagation();

                    createNote(
                        verbData,
                        "Perfekt",
                        verbData.perfektConj,
                        cellData,
                        buttonData
                    );
                };

            }(
                verb,
                perfektCell,
                perfektButton
            );

        perfektCell.appendChild(perfektButton);


        /* PRÄTERITUM */

        var praeteritumCell = document.createElement("td");

        var praeteritumButton = document.createElement("button");

        praeteritumButton.className = "verb-button";

        praeteritumButton.innerHTML = verb.praeteritum;

        praeteritumButton.onclick =
            function(verbData, cellData, buttonData) {

                return function(event) {

                    event.stopPropagation();

                    createNote(
                        verbData,
                        "Präteritum",
                        verbData.praeteritumConj,
                        cellData,
                        buttonData
                    );
                };

            }(
                verb,
                praeteritumCell,
                praeteritumButton
            );

        praeteritumCell.appendChild(praeteritumButton);


        row.appendChild(praesensCell);
        row.appendChild(perfektCell);
        row.appendChild(praeteritumCell);

        tableBody.appendChild(row);
    }
}


searchInput.onkeyup = function() {

    var searchValue =
        searchInput.value.toLowerCase();

    var filteredVerbs =
        verbs.filter(function(verb) {

            return verb.infinitive
                .toLowerCase()
                .indexOf(searchValue) !== -1;

        });

    displayVerbs(filteredVerbs);
};


